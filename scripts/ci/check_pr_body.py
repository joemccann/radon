#!/usr/bin/env python3
"""Validate a pull request body against .github/pull_request_template.md.

Every PR, whoever drafts it (an operator, an interactive agent, a nightly
runner loop, the IR pickup, the codemap job), carries the
template's six `##` sections in order, each with real content:

    Summary, What changed, Test plan, Risk and rollback,
    Operator Next Steps, Checklist

`gh pr create --body ...` never shows the template, so the template file
alone enforces nothing. This module is the one validator behind:

- the `PR body template` CI check (.github/workflows/pr-body.yml);
- the nightly runner's gh guard (scripts/nightly_pr_guard.py) and
  scripts/nightly_publish.py;
- the generated bodies of scripts/github_pr_output.py and
  scripts/ir_pr_description.py;
- the Claude Code PreToolUse hook in .claude/settings.json (`hook`).

Rules: each required heading appears exactly once as a level-2 ATX
heading outside code fences, in template order; extra headings are
allowed; a section is empty when nothing remains after HTML comments and
blank lines are removed; an unedited template placeholder fails; the
Checklist holds at least one task-list item. `None` is valid content for
Operator Next Steps.

Exemption: PRs authored by `dependabot[bot]` (exact login). Its bodies are
generated by GitHub and cannot follow a repository template. Nothing else
is exempt; the codemap nightly and every agent path write a conforming body.

Stdlib only: CI runs it with the runner's bare python3 and the gh guard
runs it with `python -I` from a root-owned lib directory.

Exit codes: 0 valid (or exempt), 1 invalid, 2 usage or I/O error.
`hook` mode exits 2 to block the tool call, per Claude Code's contract.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import sys
from pathlib import Path

TEMPLATE_PATH = ".github/pull_request_template.md"

REQUIRED_SECTIONS = (
    "Summary",
    "What changed",
    "Test plan",
    "Risk and rollback",
    "Operator Next Steps",
    "Checklist",
)

# The template's own fill-in markers. A body still carrying one was not
# written, only pasted. Kept in sync with the template by a test.
TEMPLATE_PLACEHOLDERS = (
    "<what this is and why>",
    "<files or behavior this PR changes>",
    "<command and result>",
    "<jobs that apply, or pending>",
    "<revert commit, or the rollback path if revert is not enough>",
    "<None, or the operator work still open: merge (automation never merges), "
    "secret or flag change, host package or unit install, data backfill, "
    "2FA or gateway action, follow-up outside CI.>",
    "<None, or the operator work still open: merge (nightly bot never merges; "
    "operator release coordinator may use standing policy), secret or flag "
    "change, host package or unit install, data backfill, 2FA or gateway "
    "action, follow-up outside CI.>",
)

CHECKLIST_ITEMS = (
    "Red/green TDD (failing test, then fix)",
    "Stage only the files this change owns (no `git add -A`)",
    "Owner doc updated, or the commit message has a `docs-skip:` reason",
    "Previous main deploy finished before this push",
)

EXEMPT_AUTHORS = frozenset({"dependabot[bot]"})

_COMMENT = re.compile(r"<!--.*?(?:-->|\Z)", re.S)
_HEADING = re.compile(r"^ {0,3}##[ \t]+(.+?)[ \t]*#*[ \t]*$")
_FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
_TASK = re.compile(r"^\s*[-*+]\s+\[[ xX]\]\s+\S")


def strip_comments(text: str) -> str:
    return _COMMENT.sub("", text)


def render_checklist(checked: bool = False) -> str:
    mark = "x" if checked else " "
    return "\n".join(f"- [{mark}] {item}" for item in CHECKLIST_ITEMS)


def _key(heading: str) -> str:
    return " ".join(heading.strip().rstrip(":").split()).lower()


_REQUIRED_BY_KEY = {_key(name): name for name in REQUIRED_SECTIONS}


def _split(text: str) -> list[tuple[str | None, list[str]]]:
    """[(heading or None for the preamble, body lines)], fences respected."""
    blocks: list[tuple[str | None, list[str]]] = [(None, [])]
    fence = ""
    for line in text.split("\n"):
        opener = _FENCE.match(line)
        if fence:
            if opener and opener.group(1)[0] == fence[0] and len(opener.group(1)) >= len(fence):
                fence = ""
            blocks[-1][1].append(line)
            continue
        if opener:
            fence = opener.group(1)
            blocks[-1][1].append(line)
            continue
        heading = _HEADING.match(line)
        if heading:
            blocks.append((heading.group(1), []))
        else:
            blocks[-1][1].append(line)
    return blocks


def _normalize(body: str | None) -> str:
    return strip_comments((body or "").replace("\r\n", "\n").replace("\r", "\n"))


def parse_sections(body: str | None) -> dict[str, str]:
    """Required section name -> its content (first occurrence), comments removed.

    A required section runs until the next level-2 heading of any name.
    """
    out: dict[str, str] = {}
    for heading, lines in _split(_normalize(body)):
        name = _REQUIRED_BY_KEY.get(_key(heading)) if heading else None
        if name and name not in out:
            out[name] = "\n".join(lines).strip()
    return out


def find_errors(body: str | None, *, author: str | None = None) -> list[str]:
    """Every way `body` departs from the template; [] when it conforms."""
    if author is not None and author in EXEMPT_AUTHORS:
        return []
    text = _normalize(body)
    if not text.strip():
        return ["PR body is empty"]
    errors: list[str] = []
    seen: list[str] = []
    for heading, _lines in _split(text):
        name = _REQUIRED_BY_KEY.get(_key(heading)) if heading else None
        if not name:
            continue
        if name in seen:
            if f"duplicate section: ## {name}" not in errors:
                errors.append(f"duplicate section: ## {name}")
            continue
        seen.append(name)
    for name in REQUIRED_SECTIONS:
        if name not in seen:
            errors.append(f"missing section: ## {name}")
    present = [n for n in REQUIRED_SECTIONS if n in seen]
    if seen != present:
        errors.append(
            "sections out of order: expected " + " > ".join(present)
            + "; found " + " > ".join(seen)
        )
    sections = parse_sections(body)
    for name in REQUIRED_SECTIONS:
        if name not in sections:
            continue
        content = sections[name]
        if not content:
            errors.append(f"empty section: ## {name}")
            continue
        for placeholder in TEMPLATE_PLACEHOLDERS:
            if placeholder in content:
                errors.append(f"unfilled template placeholder in ## {name}: {placeholder}")
    checklist = sections.get("Checklist")
    if checklist and not any(_TASK.match(line) for line in checklist.split("\n")):
        errors.append("## Checklist has no task-list items (- [ ] / - [x])")
    return errors


def failure_message(errors: list[str]) -> str:
    lines = [f"PR body does not follow {TEMPLATE_PATH}:"]
    lines += [f"  - {e}" for e in errors]
    lines.append(
        "Required, in order: " + ", ".join(f"## {s}" for s in REQUIRED_SECTIONS)
        + ". Copy the template, fill every section (Operator Next Steps may be `None`)."
    )
    return "\n".join(lines)


# --- Claude Code PreToolUse hook ---------------------------------------------

_GH_PR = re.compile(r"\bgh\s+pr\s+(create|edit)\b")
_HEREDOC = re.compile(r"<<-?[ \t]*(['\"]?)(\w+)\1[^\n]*\n(.*?)\n[ \t]*\2[ \t]*(?:\n|\)|$)", re.S)
_BODY_FLAGS = ("--body", "-b")
_FILE_FLAGS = ("--body-file", "-F")
_FILL_FLAGS = ("--fill", "--fill-first", "--fill-verbose", "-f")


def _flag_value(tokens: list[str], flags: tuple[str, ...]) -> str | None:
    value = None
    for i, tok in enumerate(tokens):
        for flag in flags:
            if tok == flag and i + 1 < len(tokens):
                value = tokens[i + 1]
            elif flag.startswith("--") and tok.startswith(flag + "="):
                value = tok.split("=", 1)[1]
    return value


def hook_check(command: str, cwd: str | None = None) -> list[str]:
    """Errors for a Bash command that creates or edits a PR body; [] to allow.

    Bodies the hook cannot resolve statically (a shell variable, stdin
    without a heredoc) are allowed: the CI check is the hard gate.
    """
    match = _GH_PR.search(command or "")
    if not match:
        return []
    action = match.group(1)
    tail = command[match.end():]
    try:
        tokens = shlex.split(tail.split("\n", 1)[0] if "<<" in tail else tail)
    except ValueError:
        tokens = tail.split()
    # Stop at the next shell command in a chain.
    for i, tok in enumerate(tokens):
        if tok in ("&&", "||", ";", "|"):
            tokens = tokens[:i]
            break
    if action == "create" and any(t in _FILL_FLAGS for t in tokens):
        return ["gh pr create --fill writes the body from commits; pass --body-file with the template filled in"]
    has_body = any(t in _BODY_FLAGS or t.startswith("--body=") for t in tokens)
    body_file = _flag_value(tokens, _FILE_FLAGS)
    if not has_body and body_file is None:
        return []
    heredoc = _HEREDOC.search(tail)
    body: str | None = None
    if heredoc and (has_body or body_file == "-"):
        body = heredoc.group(3) + "\n"
    elif body_file and body_file != "-":
        path = Path(body_file)
        if not path.is_absolute() and cwd:
            path = Path(cwd) / path
        try:
            body = path.read_text(encoding="utf-8")
        except OSError:
            return []
    elif has_body:
        value = _flag_value(tokens, _BODY_FLAGS)
        if value is None or "$" in value or "`" in value:
            return []
        body = value
    if body is None:
        return []
    return find_errors(body)


def _hook_main() -> int:
    try:
        payload = json.load(sys.stdin)
        command = payload.get("tool_input", {}).get("command", "")
        cwd = payload.get("cwd")
    except (ValueError, AttributeError):
        return 0
    if not isinstance(command, str):
        return 0
    errors = hook_check(command, cwd if isinstance(cwd, str) else None)
    if errors:
        print(failure_message(errors), file=sys.stderr)
        return 2
    return 0


def main(argv: list[str] | None = None) -> int:
    args_in = sys.argv[1:] if argv is None else argv
    if args_in[:1] == ["hook"]:
        return _hook_main()
    parser = argparse.ArgumentParser(description="Validate a PR body against the repo template.")
    src = parser.add_mutually_exclusive_group(required=True)
    src.add_argument("--body-file", type=Path)
    src.add_argument("--body-env", metavar="NAME", help="read the body from this environment variable")
    src.add_argument("--stdin", action="store_true")
    parser.add_argument("--author", help="PR author login (for the dependabot exemption)")
    args = parser.parse_args(args_in)
    try:
        if args.body_file is not None:
            body = args.body_file.read_text(encoding="utf-8")
        elif args.body_env:
            body = os.environ.get(args.body_env, "")
        else:
            body = sys.stdin.read()
    except (OSError, UnicodeError) as exc:
        print(f"cannot read PR body: {exc}", file=sys.stderr)
        return 2
    if args.author in EXEMPT_AUTHORS:
        print(f"PR body check: author {args.author} is exempt")
        return 0
    errors = find_errors(body, author=args.author)
    if errors:
        print(failure_message(errors), file=sys.stderr)
        return 1
    print("PR body follows " + TEMPLATE_PATH)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
